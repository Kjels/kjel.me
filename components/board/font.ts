export const glyph = (ch: string) => F[ch] || F["?"] || F["."];
export const glyphM = (ch: string) => F3[ch] || F3["."];

/** width in dots of `text` in the 5x7 face at scale 1 */
export function measureCols(text: string) {
  let w = 0;
  for (const ch of text.toUpperCase()) w += glyph(ch)[0].length + 1;
  return Math.max(0, w - 1);
}

/** width in dots of `text` in the 3x5 micro face */
export function measureM(text: string) {
  let w = 0;
  for (const ch of text.toUpperCase()) w += glyphM(ch)[0].length + 1;
  return Math.max(0, w - 1);
}

/** greedy word wrap in the 5x7 face */
export function wrap(text: string, scale: number, maxCols: number) {
  const out: string[] = [];
  let line = "";
  for (const word of text.split(" ")) {
    const probe = line ? line + " " + word : word;
    if (measureCols(probe) * scale > maxCols && line) { out.push(line); line = word; }
    else line = probe;
  }
  if (line) out.push(line);
  return out;
}

/** greedy word wrap in the micro face */
export function wrapM(text: string, maxCols: number) {
  const out: string[] = [];
  let line = "";
  for (const word of text.split(" ")) {
    const probe = line ? line + " " + word : word;
    if (measureM(probe) > maxCols && line) { out.push(line); line = word; }
    else line = probe;
  }
  if (line) out.push(line);
  return out;
}

/** drop characters the face can't stamp, collapse spaces, trim to a dot budget */
export function fit(s: string, micro: boolean, budget: number) {
  let out = "";
  for (const ch of s.toUpperCase()) if ((micro ? F3 : F)[ch] || ch === " ") out += ch;
  out = out.replace(/\s+/g, " ").trim();
  while (out && (micro ? measureM(out) : measureCols(out)) > budget) out = out.slice(0, -1).trimEnd();
  return out;
}
